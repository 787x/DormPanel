// 在官方授权的同一合成目录上验证本地/WebDAV 互操作；不授予或绕过系统 ACL。
import { readFile } from 'node:fs/promises';
import { basename, join } from 'node:path';
import assert from 'node:assert/strict';
import { Catalog } from '../src/catalog.mjs';
import { Store } from '../src/store.mjs';
import { WebDav } from '../src/webdav.mjs';
import { loadGraph } from '../src/graph.mjs';
import { ensure, decode } from '../src/protocol.mjs';
const root = process.env.PR39_TEST_DIR;
ensure(root && /^pr39-e2e-[0-9a-f-]{36}$/.test(basename(root)), '需要独立测试目录');
const authorized = (process.env.TRIM_DATA_ACCESSIBLE_PATHS ?? '').split(':').find(p => p.endsWith('/' + basename(root)));
ensure(authorized, '必须由 fnOS 官方目录授权环境提供同名测试目录');
const config = JSON.parse(await readFile(join(root, 'config.json'), 'utf8'));
ensure(new URL(config.url).pathname.endsWith('/' + basename(root) + '/'), 'WebDAV 测试范围不符');
const webConfig = { ...config, url: new URL('a/', config.url).href };
const store = await new Store(join(root, 'interop-state')).init();
const catalog = await Catalog.open({ store, configPath: join(root, 'no-legacy-config.json'), authorizedRoots: [{ id: 'official', name: 'fnOS 授权合成目录', path: authorized }] });
const manage = input => catalog.manage({ catalogVersion: catalog.manifest.revision, ...input });
const local = await manage({ action: 'connection.save', type: 'local', name: '官方授权本地端点', rootId: 'official', relative: 'a' });
const workspace = await manage({ action: 'workspace.add', connectionId: local.connectionId, name: '本地 WebDAV 互操作' });
const db = catalog.db(workspace.workspaceId);
await catalog.network(workspace.workspaceId, e => e.synchronize({ bind: true }));
await db.edit({ kind: 'entry', action: 'upsert', value: { ...db.frame.local.entries[0], title: '本地发布，WebDAV 回读' } }, db.frame.revision);
await catalog.network(workspace.workspaceId, e => e.synchronize());
const remote = new WebDav(webConfig), bytes = await remote.read(db.frame.receipt.commitId);
assert.equal(decode(bytes).state.entries[0].title, '本地发布，WebDAV 回读');
assert.equal(decode(bytes).writerId, store.identity.writerId);
assert.equal((await loadGraph(remote)).datasetId, db.frame.datasetId);
console.log('官方授权目录：包用户本地发布 → fnOS WebDAV 逐字节解码及完整 DAG PASS');
const web = await manage({ action: 'connection.save', type: 'webdav', name: '同目录 WebDAV 端点', ...webConfig });
await db.edit({ kind: 'entry', action: 'upsert', value: { ...db.frame.local.entries[0], title: '端点迁移保留离线编辑' } }, db.frame.revision);
const datasetId = db.frame.datasetId, writerId = store.identity.writerId;
await manage({ action: 'workspace.endpoint', targetId: workspace.workspaceId, targetVersion: db.frame.revision, connectionId: web.connectionId });
assert.equal(db.frame.datasetId, datasetId); assert.equal(store.identity.writerId, writerId);
await catalog.network(workspace.workspaceId, e => e.synchronize());
assert.equal(decode(await new WebDav(webConfig).read(db.frame.receipt.commitId)).state.entries[0].title, '端点迁移保留离线编辑');
console.log('本地 → WebDAV 同数据集端点完整验证、保留身份/离线编辑并发布 PASS');
const duplicate = await manage({ action: 'workspace.add', connectionId: local.connectionId, name: '重复本地地址保护' });
await assert.rejects(catalog.network(duplicate.workspaceId, e => e.synchronize({ bind: true })), /已绑定/);
console.log('同物理数据集的本地和 WebDAV 地址拒绝重复绑定 PASS');
